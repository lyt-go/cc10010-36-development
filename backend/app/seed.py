from __future__ import annotations

from typing import Any

from app.services.notifyevent_keys import idempotency_key


def _notify_event(
    event_id: int,
    *,
    batch_no: str,
    sla_id: int,
    sla_code: str,
    job: str,
    group: str,
    channel_id: int,
    channel_code: str,
    channel_type: str,
    address: str,
    template: str,
    status: str,
    result: str,
    attempts: int,
    receipt_no: str | None,
    receipt_status: str | None,
    adopted: bool,
    redundant: bool,
    quiet_note: str,
    created: str,
    pending: bool,
    abnormal: bool,
) -> dict[str, Any]:
    """构造一条通知投递事件示例，字段口径与 NotifyeventService 保持一致。"""
    return {
        "id": event_id,
        "事件编号": f"NEVT-{event_id:04d}",
        "幂等键": idempotency_key(sla_id, channel_id),
        "批次编号": batch_no,
        "批次编号列表": [batch_no],
        "SLA规则ID": sla_id,
        "规则编号": sla_code,
        "适用作业": job,
        "值班组": group,
        "渠道ID": channel_id,
        "渠道编号": channel_code,
        "渠道类型": channel_type,
        "接收地址": address,
        "消息编号": f"MSG-{sla_id:04d}-{channel_id:04d}",
        "消息模板": template,
        "事件状态": status,
        "送达结果": result,
        "投递尝试次数": attempts,
        "最大尝试次数": 3,
        "最近尝试时间": created,
        "回执编号": receipt_no,
        "回执状态": receipt_status,
        "采纳记录": adopted,
        "冗余送达": redundant,
        "静默时段结果": quiet_note,
        "快照版本": None,
        "创建时间": created,
        "更新时间": created,
        "pending": pending,
        "abnormal": abnormal,
    }


def _notify_receipt(
    receipt_id: int,
    *,
    event_id: int,
    event_no: str,
    message_no: str,
    idem_key: str,
    channel_id: int,
    receipt_type: str,
    receipt_status: str,
    detail: str,
    registered: str,
) -> dict[str, Any]:
    return {
        "id": receipt_id,
        "回执编号": f"RECP-{receipt_id:04d}",
        "事件ID": event_id,
        "事件编号": event_no,
        "消息编号": message_no,
        "幂等键": idem_key,
        "渠道ID": channel_id,
        "回执类型": receipt_type,
        "回执状态": receipt_status,
        "回执详情": detail,
        "登记时间": registered,
    }


